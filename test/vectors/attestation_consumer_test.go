// ruleIndexes lists the matched rule index of each applying file, -1 for
// none.
func ruleIndexes(sources []attest.Source, r attest.Resolution) []int {
	out := []int{}
	for _, s := range sources {
		for _, f := range s.Files {
			idx := -1
			for _, m := range r.Matches {
				if m.File == f {
					idx = m.Index
				}
			}
			out = append(out, idx)
		}
	}
	return out
}


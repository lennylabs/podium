const (
	consumerSkillMD = "---\nname: close-books\ndescription: Close the books.\nmetadata:\n  version: 1.2.0\n  sensitivity: medium\n---\n\nClose the books.\n"
	consumerAgentMD = "---\ntype: agent\nversion: 2.0.0\ndescription: Pay\nsensitivity: high\ndeprecated: true\nreplaced_by: finance/pay2\n---\n\nPay.\n"
	consumerRuleMD  = "---\ntype: rule\nversion: 1.0.0\nrule_mode: always\n---\n\nApply.\n"
)

// signedDigestOf is the package digest the signer computes for files.
func signedDigestOf(t *testing.T, files map[string]string) string {
	t.Helper()
	res := manifest.ResolvePackage(manifest.StoredDocuments([]byte(files["ARTIFACT.md"]), []byte(files["SKILL.md"])))
	sums := map[string]attest.Sum{}
	for p, b := range files {
		sums[p] = sha256.Sum256([]byte(b))
	}
	return attest.PackageDigest(attest.NewPackage(res, sums))
}

// recordCase is a declared record case: the served record, the lifecycle
// members, and the files of the signed package.
type recordCase struct {
	name       string
	rec        servedRecordVector
	deprecated string
	replacedBy string
	signed     map[string]string
}

// recordCases declares the record cases.
func recordCases(t *testing.T) []recordCase {
	t.Helper()
	synth := func(v string) string {
		b, err := manifest.SynthesizedSkillDocument(v)
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	run := attest.FileDigest([]byte("echo\n"))
	skill := servedRecordVector{ID: "finance/close-books", Version: "1.2.0", Type: "skill", Sensitivity: "medium",
		Frontmatter: synth("1.2.0"), ManifestBody: "Close the books.\n", SkillRaw: consumerSkillMD,
		Resources: map[string]string{"scripts/run.sh": run, "empty.txt": attest.FileDigest(nil)}}
	skillFiles := map[string]string{"SKILL.md": consumerSkillMD, "scripts/run.sh": "echo\n", "empty.txt": ""}
	auto := skill
	auto.Version, auto.Frontmatter = "0.0.0-auto.7", synth("0.0.0-auto.7")
	autoSkillMD := "---\nname: close-books\ndescription: Close the books.\nmetadata:\n  sensitivity: medium\n---\n\nClose the books.\n"
	auto.SkillRaw = autoSkillMD
	authored := map[string]string{"ARTIFACT.md": synth("1.2.0"), "SKILL.md": consumerSkillMD, "scripts/run.sh": "echo\n", "empty.txt": ""}
	agent := servedRecordVector{ID: "finance/pay", Version: "2.0.0", Type: "agent", Sensitivity: "high",
		Frontmatter: consumerAgentMD, ManifestBody: "Pay.\n", Resources: map[string]string{}}
	agentFiles := map[string]string{"ARTIFACT.md": consumerAgentMD}
	rule := servedRecordVector{ID: "team/apply", Version: "1.0.0", Type: "rule", Frontmatter: consumerRuleMD, ManifestBody: "Apply.\n", Resources: map[string]string{}}
	ruleFiles := map[string]string{"ARTIFACT.md": consumerRuleMD}
	with := func(r servedRecordVector, f func(*servedRecordVector)) servedRecordVector {
		r.Resources = cloneMap(r.Resources)
		f(&r)
		return r
	}
	return []recordCase{
		{name: "plain skill synthesized", rec: skill, signed: skillFiles},
		{name: "authored document equal to synthesized", rec: skill, signed: authored},
		{name: "registry-assigned version", rec: auto, signed: map[string]string{"SKILL.md": autoSkillMD, "scripts/run.sh": "echo\n", "empty.txt": ""}},
		{name: "four candidates", rec: skill, replacedBy: `"finance/new"`, signed: skillFiles},
		{name: "agent all fields", rec: agent, deprecated: "true", replacedBy: `"finance/pay2"`, signed: agentFiles},
		{name: "agent other type", rec: with(agent, func(r *servedRecordVector) { r.Type = "rule" }), deprecated: "true", replacedBy: `"finance/pay2"`, signed: agentFiles},
		{name: "agent other sensitivity", rec: with(agent, func(r *servedRecordVector) { r.Sensitivity = "low" }), deprecated: "true", replacedBy: `"finance/pay2"`, signed: agentFiles},
		{name: "agent deprecated absent", rec: agent, replacedBy: `"finance/pay2"`, signed: agentFiles},
		{name: "agent deprecated null", rec: agent, deprecated: "null", replacedBy: `"finance/pay2"`, signed: agentFiles},
		{name: "agent deprecated string", rec: agent, deprecated: `"true"`, replacedBy: `"finance/pay2"`, signed: agentFiles},
		{name: "agent replaced_by number", rec: agent, deprecated: "true", replacedBy: "1", signed: agentFiles},
		{name: "agent declared replaced_by removed", rec: agent, deprecated: "true", signed: agentFiles},
		{name: "rule replaced_by added", rec: rule, replacedBy: `"team/apply2"`, signed: ruleFiles},
		{name: "rule low for undeclared sensitivity", rec: with(rule, func(r *servedRecordVector) { r.Sensitivity = "low" }), signed: ruleFiles},
		{name: "rule manifest body differs", rec: with(rule, func(r *servedRecordVector) { r.ManifestBody = "Other.\n" }), signed: ruleFiles},
		{name: "resource at ARTIFACT.md under synthesized", rec: with(skill, func(r *servedRecordVector) { r.Resources["ARTIFACT.md"] = run }), signed: skillFiles},
		{name: "skill resource at SKILL.md", rec: with(skill, func(r *servedRecordVector) { r.Resources["SKILL.md"] = run }), signed: skillFiles},
		{name: "rule with served SKILL.md", rec: with(rule, func(r *servedRecordVector) { r.SkillRaw = consumerSkillMD }), signed: ruleFiles},
		{name: "rule registry-assigned version", rec: with(rule, func(r *servedRecordVector) { r.Version = "0.0.0-auto.1" }), signed: ruleFiles},
	}
}

// cloneMap copies a string map.
func cloneMap(m map[string]string) map[string]string {
	out := make(map[string]string, len(m))
	for k, v := range m {
		out[k] = v
	}
	return out
}

// recordCheckVectors runs steps 2 to 6 on each record case in order.
func recordCheckVectors(t *testing.T) []recordCheckVector {
	t.Helper()
	var out []recordCheckVector
	for _, c := range recordCases(t) {
		rec := version.DeliveryRecord{ID: c.rec.ID, Version: c.rec.Version, Type: c.rec.Type, Sensitivity: c.rec.Sensitivity,
			Frontmatter: c.rec.Frontmatter, ManifestBody: c.rec.ManifestBody, SkillRaw: c.rec.SkillRaw, Resources: c.rec.Resources}
		members := map[string]json.RawMessage{}
		v := recordCheckVector{Name: c.name, RequestedID: c.rec.ID, Record: c.rec, SignedDigest: signedDigestOf(t, c.signed)}
		if c.deprecated != "" {
			v.Deprecated = json.RawMessage(c.deprecated)
			members["deprecated"] = v.Deprecated
		}
		if c.replacedBy != "" {
			v.ReplacedBy = json.RawMessage(c.replacedBy)
			members["replaced_by"] = v.ReplacedBy
		}
		err := attest.CheckDocumentSlots(rec)
		if err == nil {
			err = attest.CheckManifestBody(rec)
		}
		var life attest.Lifecycle
		if err == nil {
			life, err = attest.ReadLifecycle(members)
		}
		if err == nil {
			v.Synthesized = attest.IsSynthesizedDocument(rec)
			v.Candidates, err = attest.PackageDigestCandidates(rec, life)
		}
		if err == nil {
			v.SubjectName, err = attest.ExpectedSubjectName(c.rec.ID, rec)
		}
		v.Code, v.Constraint = failureParts(t, err)
		if err != nil {
			// A refused record yields no candidate and no subject name, so
			// an implementation compares the failure alone.
			v.Synthesized, v.Candidates, v.SubjectName = false, nil, ""
		}
		v.MatchesSigned = slices.Contains(v.Candidates, v.SignedDigest)
		if v.Candidates == nil {
			v.Candidates = []string{}
		}
		out = append(out, v)
	}
	return out
}

// policyCase is a declared policy resolution case.
type policyCase struct {
	name    string
	sources []policySourceVector
	ids     []string
}

// policyResolutionVectors resolves each case's IDs.
func policyResolutionVectors(t *testing.T) []policyResolutionCase {
	t.Helper()
	signer := `{"signers":[{"issuer":"https://accounts.acme.com","identity":"alice@acme.com"}]}`
	rule := func(ids, mode string) string {
		m := ""
		if mode != "" {
			m = `,"mode":"` + mode + `"`
		}
		return `{"ids":[` + ids + `]` + m + `,"requirements":[` + signer + `]}`
	}
	file := func(rules ...string) string {
		s := `{"version":1,"rules":[`
		for i, r := range rules {
			if i > 0 {
				s += ","
			}
			s += r
		}
		return s + `]}`
	}
	cases := []policyCase{
		{"user floor raises repository none", []policySourceVector{
			{Class: "user", DefaultMode: "require", Files: []string{file(`{"ids":["personal/**"],"mode":"none"}`, rule(`"**"`, ""))}},
			{Class: "repository", DefaultMode: "warn", Files: []string{file(`{"ids":["**"],"mode":"none"}`)}},
		}, []string{"personal/x", "finance/pay", "finance/close"}},
		{"strictest default without rules", []policySourceVector{
			{Class: "repository", DefaultMode: "warn"}, {Class: "user", DefaultMode: "none"},
		}, []string{"a"}},
		{"repository require beside user warn default", []policySourceVector{
			{Class: "user", DefaultMode: "warn"},
			{Class: "repository", Files: []string{file(rule(`"finance/**"`, "require"))}},
		}, []string{"finance/pay", "other/x"}},
		{"first matching rule", []policySourceVector{
			{Class: "user", Files: []string{file(rule(`"finance/pay"`, "warn"), rule(`"finance/**"`, "require"))}},
		}, []string{"finance/pay", "finance/close", "x"}},
	}
	var out []policyResolutionCase
	for _, c := range cases {
		var sources []attest.Source
		for i, s := range c.sources {
			var files []*attest.PolicyFile
			for _, text := range s.Files {
				doc, err := attest.ParsePolicyDocument([]byte(text))
				if err != nil {
					t.Fatalf("%s: %v", c.name, err)
				}
				f, err := attest.NewPolicyFile("vector", doc, publicGoodForVectors(t), nil, time.Unix(0, 0))
				if err != nil {
					t.Fatalf("%s: %v", c.name, err)
				}
				files = append(files, f)
			}
			class := attest.UserSource
			if s.Class == "repository" {
				class = attest.RepositorySource
			}
			sources = append(sources, attest.Source{Class: class, Name: c.name + string(rune('0'+i)), DefaultMode: attest.Mode(s.DefaultMode), Files: files})
			if c.sources[i].Files == nil {
				c.sources[i].Files = []string{}
			}
		}
		p, err := attest.NewPolicy(sources...)
		if err != nil {
			t.Fatal(err)
		}
		pc := policyResolutionCase{Name: c.name, Sources: c.sources}
		for _, id := range c.ids {
			r := p.Resolve(id)
			pc.IDs = append(pc.IDs, policyIDVector{ID: id, Mode: string(r.Mode), UserMode: string(r.UserMode), RuleIndexes: ruleIndexes(sources, r)})
		}
		out = append(out, pc)
	}
	return out
}


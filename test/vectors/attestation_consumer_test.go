// batchBindingVectors declares the batch rule cases.
func batchBindingVectors(t *testing.T) []batchBindingVector {
	t.Helper()
	cases := []batchBindingVector{
		{Name: "matched out of order", Requested: []string{"a", "b"}, Entries: []batchEntryVector{{"b", "1.0.0"}, {"a", "1.0.0"}}},
		{Name: "unrequested id", Requested: []string{"a"}, Entries: []batchEntryVector{{"a", "1.0.0"}, {"x", "1.0.0"}}},
		{Name: "repeated id", Requested: []string{"a"}, Entries: []batchEntryVector{{"a", "1.0.0"}, {"a", "1.0.0"}}},
		{Name: "requested twice", Requested: []string{"a", "a"}, Entries: []batchEntryVector{{"a", "1.0.0"}, {"a", "1.0.0"}}},
		{Name: "pin of the id", Requested: []string{"a", "b"}, VersionPins: map[string]string{"b": "2.x"}, Entries: []batchEntryVector{{"a", "1.0.0"}, {"b", "3.0.0"}}},
	}
	for i, c := range cases {
		entries := make([]version.BatchEntry, len(c.Entries))
		for j, e := range c.Entries {
			entries[j] = version.BatchEntry{Status: "ok", Served: version.Served{Record: version.DeliveryRecord{ID: e.ID, Version: e.Version}}}
		}
		for _, err := range attest.BindBatch(c.Requested, c.VersionPins, entries) {
			_, con := failureParts(t, err)
			cases[i].Constraints = append(cases[i].Constraints, con)
		}
		if cases[i].VersionPins == nil {
			cases[i].VersionPins = map[string]string{}
		}
	}
	return cases
}


// vecStream frames values by hand, independently of version.WriteFramed, so
// the generated serialization is a second statement of the §4.7.6 framing.
type vecStream struct{ bytes.Buffer }

func (s *vecStream) frame(v string) {
	var n [8]byte
	binary.BigEndian.PutUint64(n[:], uint64(len(v)))
	s.Write(n[:])
	s.WriteString(v)
}

func (s *vecStream) digest() string {
	sum := sha256.Sum256(s.Bytes())
	return "sha256:" + hex.EncodeToString(sum[:])
}

func fileVectors(files map[string]string) []fileVector {
	out := make([]fileVector, 0, len(files))
	for _, p := range sortedKeys(files) {
		out = append(out, fileVector{
			Path:          p,
			ContentBase64: base64.StdEncoding.EncodeToString([]byte(files[p])),
			Digest:        attest.FileDigest([]byte(files[p])),
		})
	}
	return out
}

func strp(s string) *string { return &s }

// buildPackageVector resolves and digests one declared package and fails the
// test when Go reaches another resolution or role than the case declares, or
// when the hand-framed serialization gives another digest.
func buildPackageVector(t *testing.T, f packageForm) packageDigestVector {
	t.Helper()
	_, hasArtifact := f.files[manifest.ArtifactFile]
	_, hasSkill := f.files[manifest.SkillFile]
	res := manifest.ResolvePackage(manifest.PackageDocuments{
		ArtifactMD:    []byte(f.files[manifest.ArtifactFile]),
		HasArtifactMD: hasArtifact,
		SkillMD:       []byte(f.files[manifest.SkillFile]),
		HasSkillMD:    hasSkill,
	})
	if res.Resolved != f.resolved || res.SkillDocument() != f.skillDoc || (f.resolved && res.Fields != f.fields) {
		t.Errorf("%s: Go resolves %v %+v with skill document %v; the case declares %v %+v %v",
			f.name, res.Resolved, res.Fields, res.SkillDocument(), f.resolved, f.fields, f.skillDoc)
	}
	sums := map[string]attest.Sum{}
	for p, b := range f.files {
		sums[p] = sha256.Sum256([]byte(b))
	}
	pkg := attest.NewPackage(res, sums)

	var s vecStream
	s.frame("podium/package-digest/1")
	rv := resolutionVector{State: "unresolved"}
	if f.resolved {
		rv = resolutionVector{
			State:       "resolved",
			Type:        strp(string(f.fields.Type)),
			Sensitivity: strp(string(f.fields.Sensitivity)),
			Deprecated:  &f.fields.Deprecated,
			ReplacedBy:  strp(f.fields.ReplacedBy),
		}
		s.frame("resolved")
		s.frame(*rv.Type)
		s.frame(*rv.Sensitivity)
		s.frame(strconv.FormatBool(f.fields.Deprecated))
		s.frame(*rv.ReplacedBy)
	} else {
		s.frame("unresolved")
	}
	paths := make([]string, 0, len(pkg.Entries))
	for p := range pkg.Entries {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	entries := make([]digestEntryVector, 0, len(paths))
	for _, p := range paths {
		d := attest.FileDigest([]byte(f.files[p]))
		s.frame(p)
		s.frame(d)
		entries = append(entries, digestEntryVector{Path: p, Digest: d})
	}
	digest := attest.PackageDigest(pkg)
	if digest != s.digest() {
		t.Errorf("%s: PackageDigest = %s, the hand-framed serialization gives %s", f.name, digest, s.digest())
	}
	return packageDigestVector{
		Name:                f.name,
		Files:               fileVectors(f.files),
		SkillDocument:       f.skillDoc,
		Resolution:          rv,
		Entries:             entries,
		SerializationBase64: base64.StdEncoding.EncodeToString(s.Bytes()),
		PackageDigest:       digest,
	}
}

// buildLayerVector walks one declared layer with both walks, fails the test
// when they differ, and records the layer digest with its hand-framed
// serialization.
func buildLayerVector(t *testing.T, f layerForm) layerDigestVector {
	t.Helper()
	tree := fstest.MapFS{}
	for p, b := range f.files {
		tree[p] = &fstest.MapFile{Data: []byte(b)}
	}
	l, err := ingest.LayerContent(tree)
	if err != nil {
		t.Fatalf("%s: ingest.LayerContent: %v", f.name, err)
	}
	dir := t.TempDir()
	testharness.WriteTree(t, dir, writeOptions(f.files)...)
	fsl, err := filesystem.LayerContent(filesystem.Layer{ID: "vector", Path: dir})
	if err != nil {
		t.Fatalf("%s: filesystem.LayerContent: %v", f.name, err)
	}
	if attest.LayerDigest(fsl) != attest.LayerDigest(l) {
		t.Errorf("%s: the filesystem walk gives %s, the ingest walk %s", f.name, attest.LayerDigest(fsl), attest.LayerDigest(l))
	}

	subjects := make([]subjectVector, 0, len(l.Subjects))
	for _, s := range l.Subjects {
		subjects = append(subjects, subjectVector{Name: s.Name, PackageDigest: s.Digest})
	}
	sort.Slice(subjects, func(i, j int) bool { return subjects[i].Name < subjects[j].Name })
	layerFiles := map[string]string{}
	for p := range l.Files {
		layerFiles[p] = f.files[p]
	}

	var s vecStream
	s.frame("podium/layer-digest/1")
	s.frame(strconv.Itoa(len(subjects)))
	for _, sub := range subjects {
		s.frame(sub.Name)
		s.frame(sub.PackageDigest)
	}
	files := fileVectors(layerFiles)
	for _, fv := range files {
		s.frame(fv.Path)
		s.frame(fv.Digest)
	}
	digest := attest.LayerDigest(l)
	if digest != s.digest() {
		t.Errorf("%s: LayerDigest = %s, the hand-framed serialization gives %s", f.name, digest, s.digest())
	}
	return layerDigestVector{
		Name:                f.name,
		Subjects:            subjects,
		LayerFiles:          files,
		SerializationBase64: base64.StdEncoding.EncodeToString(s.Bytes()),
		LayerDigest:         digest,
	}
}

func writeOptions(files map[string]string) []testharness.WriteTreeOption {
	opts := make([]testharness.WriteTreeOption, 0, len(files))
	for _, p := range sortedKeys(files) {
		opts = append(opts, testharness.WriteTreeOption{Path: p, Content: files[p]})
	}
	return opts
}

// TestAttestationVectors_MatchGo builds the §4.7.6 package digest and layer
// digest cases, checks each against the resolution its case declares and
// against a serialization framed by hand, and compares the generated file
// with test/vectors/attestation.json, which the Python and TypeScript
// implementations read.
//
// Spec: §4.7.6
func TestAttestationVectors_MatchGo(t *testing.T) {
	t.Parallel()
	var pkgs []packageDigestVector
	var names []string
	for _, f := range packageForms() {
		pkgs = append(pkgs, buildPackageVector(t, f))
		names = append(names, f.name)
	}
	checkUniqueNames(t, "package_digest", names)
	var layers []layerDigestVector
	names = nil
	for _, f := range layerForms() {
		layers = append(layers, buildLayerVector(t, f))
		names = append(names, f.name)
	}
	checkUniqueNames(t, "layer_digest", names)
	if t.Failed() {
		return
	}
	file := attestationFile{
		Description:   attestationDescription,
		PackageDigest: sortByName(pkgs, func(v packageDigestVector) string { return v.Name }),
		LayerDigest:   sortByName(layers, func(v layerDigestVector) string { return v.Name }),
	}
	testharness.AssertGoldenFile(t, filepath.Join(".", attestationFileName), encodeVectors(t, file))
}

// attestationFileName is the generated cross-language file of author
// attestation vectors, beside this source.
const attestationFileName = "attestation.json"

// attestationDescription is the description member of attestation.json.
const attestationDescription = "Cross-language vectors for author attestation (§4.7.6). " +
	"Generated by test/vectors/attestation_test.go; regenerate with UPDATE_GOLDEN=1 go test ./test/vectors/. " +
	"package_digest cases give a package's files with their bytes in standard base64, the role of its root " +
	"SKILL.md, its resolution state and resolved fields, the entries the §4.7.6 entry rule keeps in ascending " +
	"byte-wise UTF-8 path order, the serialization in standard base64, and the package digest. A consumer " +
	"frames the resolution and the entries; it reads no YAML. layer_digest cases give the subjects of a layer " +
	"with their package digests, its layer files with their bytes, the serialization, and the layer digest. " +
	"Later phases add sections to this file."

// attestationFile is the layout of attestation.json. Every section is sorted
// by case name.
type attestationFile struct {
	Description   string                `json:"description"`
	PackageDigest []packageDigestVector `json:"package_digest"`
	LayerDigest   []layerDigestVector   `json:"layer_digest"`
}

// resolutionVector is a package's resolution state and resolved fields. The
// fields are absent for an unresolved package.
type resolutionVector struct {
	State       string  `json:"state"`
	Type        *string `json:"type,omitempty"`
	Sensitivity *string `json:"sensitivity,omitempty"`
	Deprecated  *bool   `json:"deprecated,omitempty"`
	ReplacedBy  *string `json:"replaced_by,omitempty"`
}

// fileVector is one file with its bytes and its file digest.
type fileVector struct {
	Path          string `json:"path"`
	ContentBase64 string `json:"content_base64"`
	Digest        string `json:"digest"`
}

// digestEntryVector is one entry of a serialization: a path and its file digest.
type digestEntryVector struct {
	Path   string `json:"path"`
	Digest string `json:"digest"`
}

type packageDigestVector struct {
	Name                string              `json:"name"`
	Files               []fileVector        `json:"files"`
	SkillDocument       bool                `json:"skill_document"`
	Resolution          resolutionVector    `json:"resolution"`
	Entries             []digestEntryVector `json:"entries"`
	SerializationBase64 string              `json:"serialization_base64"`
	PackageDigest       string              `json:"package_digest"`
}

type subjectVector struct {
	Name          string `json:"name"`
	PackageDigest string `json:"package_digest"`
}

type layerDigestVector struct {
	Name                string          `json:"name"`
	Subjects            []subjectVector `json:"subjects"`
	LayerFiles          []fileVector    `json:"layer_files"`
	SerializationBase64 string          `json:"serialization_base64"`
	LayerDigest         string          `json:"layer_digest"`
}

// packageForm declares one package case: its files, and the resolution and
// role of its root SKILL.md written from §4.7.6.
type packageForm struct {
	name     string
	files    map[string]string
	resolved bool
	skillDoc bool
	fields   manifest.ResolvedFields
}


// TestReservedNameVectors_MatchGo checks every declared segment against
// materialize.AliasesDotGit and materialize.AliasesDotPodium, and compares
// the generated corpus with test/vectors/reserved-names.json, which the
// Python and TypeScript SDK suites read.
//
// Spec: §7.5.3
func TestReservedNameVectors_MatchGo(t *testing.T) {
	t.Parallel()
	forms := reservedForms()
	cases := make([]reservedCase, 0, len(forms))
	names := make([]string, 0, len(forms))
	for _, f := range forms {
		git, podium := materialize.AliasesDotGit(f.seg), materialize.AliasesDotPodium(f.seg)
		if git != f.git || podium != f.podium {
			t.Errorf("%s (%q): Go reports names_git %v, names_podium %v; the case declares %v, %v",
				f.name, f.seg, git, podium, f.git, f.podium)
		}
		cases = append(cases, reservedCase{
			Name:        f.name,
			SegmentHex:  hex.EncodeToString([]byte(f.seg)),
			ValidUTF8:   utf8.ValidString(f.seg),
			NamesGit:    f.git,
			NamesPodium: f.podium,
		})
		names = append(names, f.name)
	}
	checkUniqueNames(t, "reserved names", names)
	if t.Failed() {
		return
	}
	file := reservedFile{
		Description: reservedDescription,
		Cases:       sortByName(cases, func(c reservedCase) string { return c.Name }),
	}
	testharness.AssertGoldenFile(t, filepath.Join(".", reservedFileName), encodeVectors(t, file))
}

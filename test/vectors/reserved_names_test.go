// reservedFileName is the generated corpus of path segments for the §7.5.3
// aliasing rule, beside this source.
const reservedFileName = "reserved-names.json"

// reservedDescription is the description member of the generated corpus.
const reservedDescription = "Cross-language corpus for the §7.5.3 aliasing rule: whether a path " +
	"segment names .git or .podium under Git's core.protectHFS and core.protectNTFS checks. " +
	"Generated by test/vectors/reserved_names_test.go; regenerate with UPDATE_GOLDEN=1 go test ./test/vectors/. " +
	"segment_hex is the segment's bytes. valid_utf8 is false when the bytes are not valid UTF-8, " +
	"which a consumer that holds names as Unicode strings cannot represent; the Python SDK decodes " +
	"them with surrogateescape, as os.fsdecode does, and the TypeScript SDK skips them. names_git and " +
	"names_podium are what materialize.AliasesDotGit and materialize.AliasesDotPodium report."

// reservedFile is the layout of reserved-names.json.
type reservedFile struct {
	Description string         `json:"description"`
	Cases       []reservedCase `json:"cases"`
}

// reservedCase is one segment and the rule's verdicts on it.
type reservedCase struct {
	Name        string `json:"name"`
	SegmentHex  string `json:"segment_hex"`
	ValidUTF8   bool   `json:"valid_utf8"`
	NamesGit    bool   `json:"names_git"`
	NamesPodium bool   `json:"names_podium"`
}

